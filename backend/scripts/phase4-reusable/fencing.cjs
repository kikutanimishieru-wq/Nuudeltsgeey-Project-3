'use strict';
const { requireSafe: check, hash, canonical } = require('./common.cjs');
const UUID = /^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/;
// Pure reference model ONLY. databaseNow is supplied by a simulated coordinator.
// This exports no SQL, connector, scheduler, retry loop or live mutation capability.
const CONTRACT = Object.freeze({ version: 1, enabled: false, mode: 'REFERENCE_MODEL_ONLY',
  requiredDatabaseGuarantees: ['durable-single-target-row', 'database-clock', 'atomic-compare-and-swap', 'shared-gate-lock-per-mutation-through-commit', 'exclusive-drain-before-generation-change', 'terminal-outcome-reconciliation', 'no-worker-bypass-privileges'],
});
function initialLease(targetDigest, epoch) {
  check(hash(targetDigest) && UUID.test(epoch), 'FENCE_INSTALLATION');
  return { version: 0, fence: 0, targetDigest, epoch, state: 'FREE', holder: null, runId: null, leaseId: null, validUntil: null, lastDatabaseTime: 0 };
}
function assertState(s) {
  check(s && Number.isSafeInteger(s.version) && s.version >= 0 && Number.isSafeInteger(s.fence) && s.fence >= 0 && hash(s.targetDigest) && UUID.test(s.epoch), 'FENCE_STATE');
  check(['FREE', 'ACTIVE', 'DRAINING', 'QUARANTINED', 'RELEASED'].includes(s.state), 'FENCE_STATE');
}
function assertAuthority(s, token, databaseNow, allowDraining = false) {
  assertState(s); check(Number.isSafeInteger(databaseNow), 'DATABASE_CLOCK');
  check(databaseNow >= s.lastDatabaseTime, 'DATABASE_CLOCK_REGRESSION');
  check(token && ['targetDigest', 'epoch', 'fence', 'leaseId', 'runId', 'holder'].every(k => token[k] === s[k]), 'STALE_FENCING_TOKEN');
  check(s.state === 'ACTIVE' || (allowDraining && s.state === 'DRAINING'), 'ADMISSION_CLOSED');
  check(Number.isSafeInteger(s.validUntil) && databaseNow < s.validUntil, 'LEASE_EXPIRED');
}
function transitionLease(state, command, databaseNow) {
  assertState(state); check(Number.isSafeInteger(databaseNow), 'DATABASE_CLOCK');
  check(databaseNow >= state.lastDatabaseTime, 'DATABASE_CLOCK_REGRESSION');
  check(command?.expectedVersion === state.version, 'FENCE_CAS_CONFLICT');
  check(state.version < Number.MAX_SAFE_INTEGER && state.fence < Number.MAX_SAFE_INTEGER, 'FENCE_OVERFLOW');
  const next = { ...state, version: state.version + 1, lastDatabaseTime: databaseNow };
  if (command.type === 'acquire') {
    // Expiration NEVER implicitly transfers authority: old backends may still commit.
    check(['FREE', 'RELEASED'].includes(state.state), 'FENCE_BUSY_OR_UNSETTLED');
    check(UUID.test(command.holder) && UUID.test(command.leaseId) && /^p4_[a-f0-9]{32}$/.test(command.runId), 'FENCE_OWNER');
    check(Number.isSafeInteger(command.ttl) && command.ttl >= 1000 && command.ttl <= 600000 && Number.isSafeInteger(databaseNow + command.ttl), 'LEASE_TTL');
    return { ...next, fence: state.fence + 1, state: 'ACTIVE', holder: command.holder, runId: command.runId, leaseId: command.leaseId, validUntil: databaseNow + command.ttl };
  }
  if (command.type === 'quarantine') {
    check(['ACTIVE', 'DRAINING'].includes(state.state), 'FENCE_STATE');
    return { ...next, state: 'QUARANTINED' };
  }
  assertAuthority(state, command.token, databaseNow, true);
  if (command.type === 'renew') {
    check(state.state === 'ACTIVE', 'ADMISSION_CLOSED');
    check(Number.isSafeInteger(command.ttl) && command.ttl >= 1000 && command.ttl <= 600000, 'LEASE_TTL');
    check(Number.isSafeInteger(databaseNow + command.ttl) && databaseNow + command.ttl > state.validUntil, 'LEASE_RENEWAL');
    return { ...next, validUntil: databaseNow + command.ttl };
  }
  if (command.type === 'drain') return { ...next, state: 'DRAINING' };
  // Release/recovery deliberately unavailable: proof must be generated by a real
  // database supervisor holding the exclusive gate and reconciling all sessions.
  throw new Error('FENCE_RELEASE_REQUIRES_DATABASE_PROOF');
}
function tokenOf(state) {
  return Object.fromEntries(['targetDigest', 'epoch', 'fence', 'leaseId', 'runId', 'holder'].map(k => [k, state[k]]));
}
function verifyMutationProof(proof, receipt, installation) {
  check(proof && proof.protocol === 'shared-gate-v1' && proof.targetDigest === receipt.targetDigest && proof.epoch === installation.epoch, 'MUTATION_FENCE_PROOF');
  check(proof.fence === receipt.leaseFence && proof.leaseId === receipt.leaseId && proof.transactionId === receipt.transactionId && proof.xid === receipt.xid, 'MUTATION_FENCE_BINDING');
  check(canonical(proof.session) === canonical(receipt.session), 'MUTATION_SESSION_BINDING');
  check(Number.isSafeInteger(proof.databaseTime) && Number.isSafeInteger(proof.validUntil) && proof.databaseTime < proof.validUntil, 'LEASE_EXPIRED');
  check(proof.gateHeldThroughCommit === true && proof.sameTransactionCapture === true && proof.privilegeBypassExcluded === true, 'ATOMIC_FENCING_UNPROVEN');
  check(Number.isSafeInteger(proof.mutationCount) && proof.mutationCount === receipt.operations.length && proof.mutationCount > 0, 'MUTATION_COVERAGE');
  // These assertions are authoritative only within independently signed observer
  // evidence. Passing this pure comparison is NOT a database fencing permit.
}
function authorizeDatabaseMutation() { throw new Error('ATOMIC_DATABASE_FENCING_NOT_INSTALLED'); }
module.exports = { CONTRACT, UUID, initialLease, tokenOf, assertAuthority, transitionLease, verifyMutationProof, authorizeDatabaseMutation };
